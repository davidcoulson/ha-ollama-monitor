"""Build the logo SVGs from icon.svg and render the brand PNGs.

Usage: python3 assets/brand/render.py
Needs Google Chrome (headless rendering) and ImageMagick (`magick`).
Writes logo.svg / dark_logo.svg here and the PNGs to
custom_components/ollama_monitor/brand/.
"""

from __future__ import annotations

from pathlib import Path
import re
import subprocess
import tempfile

HERE = Path(__file__).parent
TARGET = HERE.parent.parent / "custom_components" / "ollama_monitor" / "brand"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
WORDMARK = "Ollama Monitor"
FONT = "'Helvetica Neue', Helvetica, Arial, sans-serif"


def build_logo(text_color: str) -> str:
    """Return a logo SVG: the icon followed by the wordmark, 512 px high."""
    icon = (HERE / "icon.svg").read_text()
    inner = re.search(r"<svg[^>]*>(.*)</svg>", icon, re.S)
    if inner is None:
        raise ValueError("icon.svg has no <svg> element")
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="2400" height="512" '
        'viewBox="0 0 2400 512">\n'
        "  <!-- Generated by render.py from icon.svg -->\n"
        f"{inner.group(1)}"
        f'  <text x="576" y="256" dominant-baseline="central" font-family="{FONT}" '
        f'font-size="210" font-weight="600" fill="{text_color}">{WORDMARK}</text>\n'
        "</svg>\n"
    )


def render(svg: Path, width: int, height: int, out: Path) -> None:
    """Render an SVG with headless Chrome on a transparent background."""
    subprocess.run(
        [
            CHROME,
            "--headless",
            "--disable-gpu",
            "--hide-scrollbars",
            "--default-background-color=00000000",
            "--force-device-scale-factor=1",
            f"--window-size={width},{height}",
            f"--screenshot={out}",
            svg.resolve().as_uri(),
        ],
        check=True,
        capture_output=True,
    )


def finish(src: Path, height: int, out: Path) -> None:
    """Trim transparent edges, scale to the target height and optimize."""
    subprocess.run(
        [
            "magick",
            str(src),
            "-trim",
            "+repage",
            "-filter",
            "Lanczos",
            "-resize",
            f"x{height}",
            "-strip",
            "-define",
            "png:compression-level=9",
            "-define",
            "png:compression-filter=5",
            f"PNG32:{out}",
        ],
        check=True,
    )


def main() -> None:
    """Render every brand image."""
    (HERE / "logo.svg").write_text(build_logo("#0F172A"))
    (HERE / "dark_logo.svg").write_text(build_logo("#F8FAFC"))
    TARGET.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        raw_icon = Path(tmp) / "icon.png"
        render(HERE / "icon.svg", 512, 512, raw_icon)
        finish(raw_icon, 256, TARGET / "icon.png")
        finish(raw_icon, 512, TARGET / "icon@2x.png")
        for name in ("logo", "dark_logo"):
            raw = Path(tmp) / f"{name}.png"
            render(HERE / f"{name}.svg", 2400, 512, raw)
            finish(raw, 256, TARGET / f"{name}.png")
            finish(raw, 512, TARGET / f"{name}@2x.png")


if __name__ == "__main__":
    main()
